package com.github.guoyyit.canopenstackjava.canopen.od;

/**
 * SDO/对象字典访问中止码（CiA 301 标准错误码）。
 */
public enum AbortCode {

    NO_ERROR(0x00000000),
    TOGGLE_BIT_INVALID(0x05030000),
    SDO_PROTOCOL_ERROR(0x05040001),
    SDO_COMMAND_SPECIFIER_INVALID(0x05040002),
    OUT_OF_MEMORY(0x05040005),
    UNSUPPORTED_ACCESS(0x06010000),
    READ_ON_WRITE_ONLY(0x06010001),
    WRITE_ON_READ_ONLY(0x06010002),
    SDO_TIMEOUT(0x06010003),
    UNSUPPORTED_ACCESS_TO_OBJECT(0x06010005),
    WRONG_DEVICE_STATE(0x0601000A),
    OBJECT_DOES_NOT_EXIST(0x06020000),
    PDO_MAP_INVALID(0x06040041),
    PDO_LENGTH_EXCEEDED(0x06040042),
    PARAMETER_INCOMPATIBILITY(0x06040043),
    INTERNAL_INCOMPATIBILITY(0x06070010),
    SUBINDEX_DOES_NOT_EXIST(0x06090011),
    VALUE_TOO_HIGH(0x06090030),
    VALUE_TOO_LOW(0x06090031),
    VALUE_RANGE_OVERFLOW(0x06090032),
    GENERAL_ERROR(0x08000000),
    DATA_CANNOT_TRANSFERRED(0x08000020);

    private final int code;

    AbortCode(int code) {
        this.code = code;
    }

    public int getCode() {
        return code;
    }
}
